/**
 * Line icons for the admin console sidebar — SCRUM-217.
 *
 * Same hand-rolled approach as `app/realtor/_icons.tsx`, `app/_landing/icons.tsx`
 * and `app/_onboarding/icons.tsx`: one 24×24 stroked frame, no icon dependency.
 * Icons inherit colour and size from the caller (`currentColor`, `h-*`/`w-*`),
 * so a caller always sets a size — there is no sensible default.
 */

type IconProps = {
  className?: string;
  /** Stroke weight. 1.8 reads correctly at 20-24px; drop to 1.6 below that. */
  strokeWidth?: number;
};

function Svg({
  className,
  strokeWidth = 1.8,
  children,
}: IconProps & { children: React.ReactNode }) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      aria-hidden
    >
      {children}
    </svg>
  );
}

